package com.luma.ledcontroller.core.model

import kotlinx.serialization.Serializable

/**
 * The kinds of motion a mode can ask for.
 *
 * These are the animation parameters the eventual controller receives. Nothing in this UI-shell
 * build drives LEDs, so every kind is a stored parameter that the editor previews.
 */
@Serializable
enum class AnimationKind {
    /** No motion: the ramp is mapped along the strip and stays there. */
    SOLID,

    /** The whole strip breathes in output level, following the ramp's position. */
    BREATHE,

    /** The ramp scrolls along the strip. */
    CHASE,

    /** Individual pixels light up along the ramp at random positions. */
    TWINKLE,
}

/**
 * Animation parameters for a mode.
 *
 * @param kind the kind of motion.
 * @param speed `0f..1f`, where 0 is the slowest supported motion and 1 the fastest.
 * @param spread `0f..1f`, the spatial fraction of the strip the motion covers. Only meaningful for
 *   [AnimationKind.CHASE] and [AnimationKind.TWINKLE].
 * @param reverse reverses the direction of travel.
 */
@Serializable
data class ModeAnimation(
    val kind: AnimationKind = AnimationKind.SOLID,
    val speed: Float = 0.35f,
    val spread: Float = 0.5f,
    val reverse: Boolean = false,
) {
    fun normalised(): ModeAnimation = copy(
        speed = speed.coerceIn(0f, 1f),
        spread = spread.coerceIn(0f, 1f),
    )

    companion object {
        val Default = ModeAnimation()
    }
}

/**
 * A named, reusable mode (scene).
 *
 * Modes are independent data objects: they own their colour ramp and animation parameters and know
 * nothing about strips. A strip references a mode by [LumaStrip.modeId], and a [LumaSchedule]
 * references one too, which is what makes a mode reusable and schedulable without duplicating its
 * configuration.
 *
 * @param id stable identifier, generated by the app.
 * @param name human readable name, shown in pickers and schedules.
 * @param ramp the colour ramp for this mode.
 * @param animation motion parameters stored for the eventual controller.
 * @param createdAtEpochMillis creation time, used for stable ordering.
 * @param updatedAtEpochMillis last time the mode was saved.
 */
@Serializable
data class LumaMode(
    val id: String,
    val name: String,
    val ramp: ColorRamp,
    val animation: ModeAnimation = ModeAnimation.Default,
    val createdAtEpochMillis: Long = 0L,
    val updatedAtEpochMillis: Long = 0L,
) {
    /** Short description used in pickers: "Solid", "Gradient · 4 stops", ... */
    val stopCount: Int
        get() = ramp.stops.size

    val isGradient: Boolean
        get() = ramp.stops.size > 1
}
